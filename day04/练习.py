class Animal:
    total = 0                          # 题 2：类属性

    def __init__(self, name, sound):
        self.name = name
        self.sound = sound
        Animal.total += 1              # 题 2：每次构造 +1

    def speak(self):
        print(f"{self.name} says {self.sound}")


class Cat(Animal):                     # 题 3：继承
    def __init__(self, name):
        super().__init__(name, "Meow") # 题 3：复用父类 __init__

    def speak(self):                   # 题 4：重写
        print("🐱 ", end="")
        super().speak()                # 题 4：复用父类 speak


# 测试
Animal("Dog", "Woof").speak()          # Dog says Woof
