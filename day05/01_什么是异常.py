# -*- coding: utf-8 -*-
"""
01 - 什么是异常？为什么要处理？

异常 = 程序运行时"出乎意料"的事情。
默认情况下，一旦出异常，整个程序直接崩掉。
"异常处理"就是把这种意外接住，不让程序死。
"""

# ============================================================
# 1. 不处理 vs 处理 —— 直观对比
# ============================================================

# 【不处理】下面这行会让整个程序立刻崩溃，后面的代码一行都不执行
# 取消下面注释你会看到：ZeroDivisionError: division by zero
#
# print(10 / 0)
# print("我永远不会被执行")


# 【处理】异常被接住，程序照常往下走
try:
    print("尝试: 10 / 0 =", 10 / 0)
except ZeroDivisionError:
    print("不能除以 0，但我接住了，程序继续")

print("我还活着！")


# ============================================================
# 2. 异常长什么样？看一下崩溃信息
# ============================================================
# 程序崩溃时 Python 会打印一段"堆栈追踪 (Traceback)"，
# 内容大致是：
#
#   Traceback (most recent call last):
#     File "xxx.py", line 30, in <module>
#       int("abc")
#   ValueError: invalid literal for int() with base 10: 'abc'
#                ^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^^
#                       ↑ 这就是异常的"信息"
#   ^^^^^^^^^^
#       ↑ 这是异常的"类型"
#
# 看到 Traceback 时要做的两件事：
#   1. 从下往上看，最下面的一行告诉你 "什么类型 + 什么原因"
#   2. 中间的 File ... line ... 告诉你"在哪一行出的"


# ============================================================
# 3. 在测试场景里为什么重要 —— 一个真实例子
# ============================================================
test_cases = ["1", "22", "abc", "44", "5x", "66"]

print("\n--- 不处理异常 ---")
# 下面这段如果取消注释，跑到 "abc" 就崩了，"44" 之后的根本不跑
# total = 0
# for s in test_cases:
#     total += int(s)


print("--- 用 try/except 处理 ---")
total = 0
failed = []
for s in test_cases:
    try:
        total += int(s)
    except ValueError:
        # 抓住"转不了整数"这种异常，记下来继续跑
        failed.append(s)

print(f"成功累加结果: {total}")
print(f"失败的输入:   {failed}")


# ============================================================
# 4. 异常处理 ≠ "让所有错误都没事"
# ============================================================
# 异常处理是"知道某种错误可能发生，并设计了应对方案"。
# 不该把所有错误都吞了 —— 程序该崩的时候让它崩，你才能发现 bug。
